function fillMantra(): void {
  if (!mantraTrack || !mantraTemplate) return;
  mantraTrack.replaceChildren(mantraTemplate);
  const groupWidth = mantraTemplate.getBoundingClientRect().width;
  if (!groupWidth) return;
  const copies = Math.ceil(window.innerWidth / groupWidth) + 2;
  for (let index = 1; index < copies; index += 1) {
    mantraTrack.append(mantraTemplate.cloneNode(true));
  }
  mantraTrack.style.setProperty("--mantra-shift", `${-groupWidth}px`);
}
